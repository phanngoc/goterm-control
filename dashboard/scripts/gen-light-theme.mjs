// Generates src/theme-light.css: the light theme as Tailwind's own palette
// turned upside down. Every utility reads its color from a CSS variable in
// Tailwind v4 (bg-gray-950 is var(--color-gray-950)), so swapping each shade
// with its mirror — 50↔950, 100↔900 … 500 stays — makes the dark UI light
// without touching a single className: the page background becomes the
// lightest gray, body text the darkest, and accent text (sky-300 on dark)
// becomes sky-700, readable on white.
//
//   node scripts/gen-light-theme.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const theme = readFileSync(join(here, '../node_modules/tailwindcss/theme.css'), 'utf8')
const shades = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950']
const colors = {}
for (const m of theme.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) {
  ;(colors[m[1]] ??= {})[m[2]] = m[3].trim()
}
const lines = []
const kept = []
for (const [name, scale] of Object.entries(colors)) {
  if (shades.some(s => !scale[s])) continue
  shades.forEach((s, i) => lines.push(`  --color-${name}-${s}: ${scale[shades[shades.length - 1 - i]]};`))
  shades.forEach(s => kept.push(`  --color-${name}-${s}: ${scale[s]};`))
}
// .dark-island puts the palette back the right way up inside an element that
// is dark in both themes — the project editor, a VS Code look whose own
// backgrounds are fixed dark colors. Without it the light theme flipped the
// text inside to dark-on-dark.
const css = `/* GENERATED by scripts/gen-light-theme.mjs — do not edit by hand. */
html.light {
  color-scheme: light;
${lines.join('\n')}
}
html.light .dark-island {
  color-scheme: dark;
${kept.join('\n')}
}
`
writeFileSync(join(here, '../src/theme-light.css'), css)
console.log(`theme-light.css: ${Object.keys(colors).length} palettes, ${lines.length} variables`)
